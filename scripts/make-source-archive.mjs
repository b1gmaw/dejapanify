/**
 * Builds the source archive submitted for add-on review.
 *
 * Mozilla requires the source for bundled extensions, and reviewers rebuild it
 * and diff the result against the uploaded package. A plain `git archive` does
 * that job, but it lands as a tree with no manifest.json in it -- because the
 * manifest and the bundles are generated -- which reasonably reads as a broken
 * or wrong upload. So the archive carries a plain-text note at its root saying
 * exactly that, at the moment someone would otherwise be confused.
 *
 * Contents are taken from HEAD rather than the working tree, and written with
 * the project's deterministic ZIP writer, so the archive is reproducible too.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { createZip } from './zip.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = createRequire(import.meta.url)(join(ROOT, 'package.json'));

const NOTE = `dejapanify ${pkg.version} — source code archive
===============================================

This archive is the project's SOURCE. It is NOT an installable extension.

There is no manifest.json in here. The manifest and the JavaScript bundles
are generated by the build, so they exist only in the build output.


BUILD INSTRUCTIONS
------------------

1. Environment

   Operating system:  Ubuntu 24.04 LTS, ARM64 or x86_64
   Node.js:           24.14.0  (also in .nvmrc)
   npm:               11.9.0   (ships with Node 24.14.0)

   Nothing else is needed: no system packages, no global npm installs, no
   web-based tools. The only network access is "npm ci" downloading the
   pinned dependencies from the public npm registry. Exact versions of every
   build dependency are pinned in the committed package-lock.json.

2. Install Node.js 24.14.0 (skip if "node --version" prints v24.14.0)

   Official binary, no root needed. On x86_64, use "linux-x64" in place of
   "linux-arm64":

       curl -O https://nodejs.org/dist/v24.14.0/node-v24.14.0-linux-arm64.tar.xz
       tar -xf node-v24.14.0-linux-arm64.tar.xz
       export PATH="$PWD/node-v24.14.0-linux-arm64/bin:$PATH"

   Or with nvm:  nvm install 24.14.0

   Check:  node --version   ->  v24.14.0
           npm --version    ->  11.9.0

3. Build, from the directory this file is in

       npm ci
       npm run build

   That writes:

       dist/firefox/     the Firefox package, manifest.json included
       dist/chrome/      the Chromium package

   The submitted add-on corresponds to dist/firefox/.

4. Compare with the submitted add-on

       unzip dejapanify-${pkg.version}-firefox.zip -d submitted
       diff -r -x META-INF submitted dist/firefox && echo IDENTICAL

   -x META-INF ignores the signature folder of a signed add-on. Compare the
   unpacked files rather than zip checksums: the zip container's compressed
   bytes depend on the zlib inside whichever Node build compressed them,
   while the files themselves are identical.


The build is deterministic: it embeds no timestamps, hashes or build IDs.
These exact steps were run before release, with Node 24.14.0 and npm 11.9.0
on Ubuntu (x86_64), starting from this archive unpacked into an empty
directory. The result matched the submitted add-on file for file. The
lockfile also pins esbuild's native binary for ARM64 builders.

Full build notes, the source map, and what the extension does:

    docs/REVIEWER_NOTES.md

The extension makes no network requests and collects no data. It has no
fetch, XMLHttpRequest, WebSocket or sendBeacon anywhere, requests only the
"storage" permission, and declares no host permissions. This is enforced by
tests/privacy.test.ts, which scans the built package and fails the build if a
network primitive appears:

    npm test
`;

function filesAtHead() {
  const out = execFileSync('git', ['ls-tree', '-r', 'HEAD', '--name-only', '-z'], { cwd: ROOT });
  return out.toString('utf8').split('\0').filter(Boolean);
}

function readAtHead(path) {
  return execFileSync('git', ['show', `HEAD:${path}`], { cwd: ROOT, maxBuffer: 1024 * 1024 * 256 });
}

export function makeSourceArchive(outFile = join(ROOT, 'web-ext-artifacts', `dejapanify-${pkg.version}-source.zip`)) {
  const dirty = execFileSync('git', ['status', '--porcelain'], { cwd: ROOT }).toString().trim();
  if (dirty) {
    console.warn('warning: working tree has uncommitted changes; archiving HEAD, not the working tree');
  }

  const entries = filesAtHead().map((name) => ({ name, data: readAtHead(name) }));
  entries.push({ name: 'REVIEWERS-README.txt', data: Buffer.from(NOTE, 'utf8') });

  mkdirSync(dirname(outFile), { recursive: true });
  const buf = createZip(entries);
  writeFileSync(outFile, buf);
  return { outFile, count: entries.length, bytes: buf.length };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { outFile, count, bytes } = makeSourceArchive();
  console.log(`source archive: ${outFile} (${count} entries, ${(bytes / 1024).toFixed(0)} KB)`);
}
